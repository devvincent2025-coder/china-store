<?php

namespace App\Filament\Resources;

use App\Filament\Concerns\AuthorizesViaPermissions;
use App\Filament\Resources\RoleResource\Pages;
use Filament\Forms;
use Filament\Forms\Form;
use Filament\Resources\Resource;
use Filament\Tables;
use Filament\Tables\Table;
use Spatie\Permission\Models\Permission;
use Spatie\Permission\Models\Role;

/**
 * Role/permission management — this is how a super_admin creates the sub-admin roles (Support
 * Admin, Finance Admin, Ads/Campaigns Admin, KYC Admin, Audit Admin, or any others) and controls
 * exactly what each one can see/do in the panel via the checkbox permission matrix below. Every
 * permission here is generated by database/seeders/AdminPermissionSeeder and checked by
 * App\Filament\Concerns\AuthorizesViaPermissions on each Resource — a role with none of a
 * resource's permissions simply never sees that resource in the sidebar. 'access_admin_panel' is
 * the one permission that actually lets a role log into /admin at all (see
 * User::canAccessPanel()) — a role without it can be fully configured here but still can't sign in.
 * Renaming/deleting the seeded 'super_admin'/'admin'/'vendor'/'buyer' roles would break the checks
 * that reference them by name (Gate::before, 'role:vendor' middleware, User::isVendor()), so this
 * intentionally allows creating new roles freely but doesn't stop an admin from editing the seeded
 * ones — that risk is accepted the same way a superuser can always shoot themselves in the foot in
 * any admin panel.
 */
class RoleResource extends Resource
{
    use AuthorizesViaPermissions;

    protected static ?string $model = Role::class;

    protected static ?string $navigationIcon = 'heroicon-o-shield-check';

    protected static ?string $navigationGroup = 'People';

    public static function form(Form $form): Form
    {
        return $form
            ->schema([
                Forms\Components\TextInput::make('name')->required()->unique(ignoreRecord: true),
                Forms\Components\CheckboxList::make('permissions')
                    ->relationship('permissions', 'name')
                    ->options(fn () => Permission::query()->pluck('name', 'id')
                        ->map(fn (string $name) => (string) str($name)->replace('_', ' ')->title()))
                    ->columns(3)
                    ->bulkToggleable()
                    ->helperText('What this role can see and do in the admin panel. "Access Admin Panel" is required for the role to be able to log in at all — everything else just narrows what they see once in.'),
            ]);
    }

    public static function table(Table $table): Table
    {
        return $table
            ->columns([
                Tables\Columns\TextColumn::make('name')->searchable()->sortable(),
                Tables\Columns\TextColumn::make('users_count')->counts('users')->label('Users'),
                Tables\Columns\TextColumn::make('permissions_count')->counts('permissions')->label('Permissions'),
                Tables\Columns\TextColumn::make('created_at')->dateTime()->sortable(),
            ])
            ->actions([
                Tables\Actions\EditAction::make(),
                Tables\Actions\DeleteAction::make(),
            ])
            ->bulkActions([]);
    }

    public static function getPages(): array
    {
        return [
            'index' => Pages\ListRoles::route('/'),
            'create' => Pages\CreateRole::route('/create'),
            'edit' => Pages\EditRole::route('/{record}/edit'),
        ];
    }
}
